#!/usr/bin/env python3
"""Render the static EN/TR public status pages from live/data.json."""
import json
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / "live/data.json").read_text(encoding="utf-8"))
if DATA.get("source") != "open-ops-lab":
    raise SystemExit("source must be open-ops-lab")
if not isinstance(DATA.get("sample"), bool):
    raise SystemExit("sample must be boolean")
for key in ("generated_at", "uptime_percent"):
    if DATA.get(key) is not None and not isinstance(DATA[key], (str, int, float)):
        raise SystemExit(f"{key} must be null, text, or numeric")
if DATA.get("uptime_percent") is not None and not 0 <= float(DATA["uptime_percent"]) <= 100:
    raise SystemExit("uptime_percent must be between 0 and 100")
if not isinstance(DATA.get("slo", []), list) or not isinstance(DATA.get("alarms", []), list):
    raise SystemExit("slo and alarms must be arrays")

FAVICON = "data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 11 11' shape-rendering='crispEdges'%3E%3Crect width='11' height='11' fill='%2316233f'/%3E%3Cpath fill='%23f5f0e6' d='M6 2h1v3H6zM1 5h3v1H1zM5 5h5v1H5zM1 6h1v2H1zM3 6h1v2H3zM5 6h1v2H5zM9 6h1v2H9zM1 8h9v1H1z'/%3E%3C/svg%3E"

def card(title, value, detail=""):
    heading = f'<h3>{escape(title)}</h3>' if title else ""
    extra = f'<p class="meta">{escape(detail)}</p>' if detail else ""
    return f'<li class="status-card">{heading}<p class="status-val">{escape(value)}</p>{extra}</li>'

def build(tr=False):
    lang = "tr" if tr else "en"
    path = "/tr/live/" if tr else "/live/"
    og_image = "/og/tr/live.png" if tr else "/og/live.png"
    title = "Üretim durumu · örnek veri" if tr else "Production status · sample data"
    intro = "Bu statik pano open-ops-lab dışa aktarım şemasını kullanır." if tr else "This static page uses the open-ops-lab export schema."
    sample = "Örnek veri — canlı bağlantı yapılandırılmadı." if tr else "Sample data — no live connection is configured."
    unavailable = "Bağlı değil" if tr else "Not connected"
    uptitle = "Çalışma süresi" if tr else "Uptime"
    slotitle = "SLO hedefleri" if tr else "SLOs"
    alarmtitle = "Son alarmlar" if tr else "Recent alarms"
    source = "Veri kaynağı: open-ops-lab → live/data.json · üretim: scripts/build-live.py" if tr else "Data source: open-ops-lab → live/data.json · generated by scripts/build-live.py"
    value = (f'{float(DATA["uptime_percent"]):g}%' if DATA.get("uptime_percent") is not None else unavailable)
    slos = DATA.get("slo", [])
    alarms = DATA.get("alarms", [])
    slo_html = "".join(card(x.get("name", "SLO"), str(x.get("actual") if x.get("actual") is not None else unavailable), f'target: {x.get("target") if x.get("target") is not None else unavailable} · {x.get("status", unavailable)}') for x in slos)
    alarm_html = "".join(card(x.get("severity", "Alarm"), x.get("summary", ""), x.get("time", "")) for x in alarms)
    if not slo_html:
        slo_html = card("", unavailable)
    if not alarm_html:
        alarm_html = card("", unavailable)
    generated = DATA.get("generated_at") or unavailable
    sample_badge = f'<p class="box" role="note">{escape(sample)}</p>' if DATA.get("sample") else ""
    structured = json.dumps({"@context":"https://schema.org","@type":"WebPage","name":title,"description":intro,"inLanguage":lang,"url":"https://tahabagatur.com"+path}, ensure_ascii=False, separators=(",", ":"))
    marker = '<!-- Cloudflare Web Analytics insertion point: token supplied by Taha. -->\n<!-- <script type="module" src="https://static.cloudflareinsights.com/beacon.min.js" data-cf-beacon="{&quot;token&quot;:&quot;TOKEN_FROM_TAHA&quot;}"></script> -->'
    if tr:
        nav = '<nav aria-label="Bölümler"><a href="/tr/#work">Vakalar</a><a href="/tr/notes/">Notlar</a><a href="/tr/#divan">Divan</a><a href="/tr/#ask">Danış bana</a></nav>'
        crumb = '<a href="/tr/">Ana sayfa</a> › Canlı durum'
        feed_link = '<a href="/tr/feed.xml">Atom akışı</a>'
        footer_text = f'© 2026 Taha Bagatur · Çerez yok. · {feed_link}'
    else:
        nav = '<nav aria-label="Sections"><a href="/#work">Cases</a><a href="/notes/">Notes</a><a href="/#divan">Divan</a><a href="/#ask">Ask me</a></nav>'
        crumb = '<a href="/">Home</a> › Live'
        feed_link = '<a href="/feed.xml">Atom feed</a>'
        footer_text = f'© 2026 Taha Bagatur · No cookies. · {feed_link}'
    html = f'''<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{escape(title)} · Taha Bagatur</title>
<meta name="description" content="{escape(intro)}">
<meta name="author" content="Taha Bagatur">
<meta name="color-scheme" content="light dark">
<meta name="theme-color" content="#f5f0e6" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#0f1622" media="(prefers-color-scheme: dark)">
<link rel="canonical" href="https://tahabagatur.com{path}">
<link rel="alternate" hreflang="en" href="https://tahabagatur.com/live/">
<link rel="alternate" hreflang="tr" href="https://tahabagatur.com/tr/live/">
<link rel="alternate" hreflang="x-default" href="https://tahabagatur.com/live/">
<link rel="icon" href="{FAVICON}">
<link rel="stylesheet" href="/assets/site.css?v=20261124">
<script type="application/ld+json">{structured}</script>
<meta property="og:title" content="{escape(title)}">
<meta property="og:description" content="{escape(intro)}">
<meta property="og:url" content="https://tahabagatur.com{path}">
<meta property="og:image" content="https://tahabagatur.com{og_image}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="{escape(title)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{escape(title)}">
<meta name="twitter:description" content="{escape(intro)}">
<meta name="twitter:image" content="https://tahabagatur.com{og_image}">
<meta name="twitter:image:alt" content="{escape(title)}">
</head>
<body>
<!--email_off-->
<a class="skip" href="#main">{'İçeriğe geç' if tr else 'Skip to content'}</a>
<header>
  <div class="wrap">
    <a class="brand" href="{'/tr/' if tr else '/'}"><svg class="seal" viewBox="0 0 11 11" shape-rendering="crispEdges" aria-hidden="true"><rect class="s-bg" width="11" height="11"/><path class="s-fg" d="M6 2h1v3H6zM1 5h3v1H1zM5 5h5v1H5zM1 6h1v2H1zM3 6h1v2H3zM5 6h1v2H5zM9 6h1v2H9zM1 8h9v1H1z"/></svg>Taha Bagatur</a>
    <div class="top">
      {nav}
      <a class="lang" href="{'/live/' if tr else '/tr/live/'}" hreflang="{'en' if tr else 'tr'}" lang="{'en' if tr else 'tr'}">{'English' if tr else 'Türkçe'}</a>
    </div>
  </div>
</header>
<main id="main">
  <div class="wrap article">
    <p class="crumbs">{crumb}</p>
    <h1>{escape(title)}</h1>
    <p class="lead">{escape(intro)}</p>
    {sample_badge}
    <p class="meta">{escape(source)}<br>{('Son üretim zamanı' if tr else 'Last generated')}: <time>{escape(str(generated))}</time></p>
    <section>
      <h2>{escape(uptitle)}</h2>
      <ul class="status-list">{card("", value)}</ul>
    </section>
    <section>
      <h2>{escape(slotitle)}</h2>
      <ul class="status-list">{slo_html}</ul>
    </section>
    <section>
      <h2>{escape(alarmtitle)}</h2>
      <ul class="status-list">{alarm_html}</ul>
    </section>
  </div>
</main>
{marker}
<footer>
  <div class="wrap">{footer_text}</div>
</footer>
<!--/email_off-->
</body>
</html>
'''
    out = ROOT / ("tr/live/index.html" if tr else "live/index.html")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")

build(False)
build(True)
